"""Build eclipse logo TS paths, report wordmarks and the O favicon SVGs from redshadow-logo eclipse SVG.

Usage: python3 logo-src/build_brand.py   (then rasterise PNG/ICO with logo-src/raster_icons.sh)
"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "frontend/public/brand/redshadow-eclipse-ink.svg").read_text()
vb = re.search(r'viewBox="([^"]+)"', src).group(1)
wedge, ink = re.findall(r' d="([^"]+)"', src)
subs = re.findall(r"M[^M]*", ink)
# The O: outer rounded rect starts at x=650.3 and its hole starts at x=649.3 (see eclipse SVG).
o_outer = next(s for s in subs if s.startswith("M650.3 0"))
o_hole = next(s for s in subs if s.startswith("M649.3 17"))
RED, INK, PAPER = "#ff2a1a", "#1f3038", "#ffffff"

(root / "frontend/src/design/logo-paths.ts").write_text(
    "// Generated by logo-src/build_brand.py from redshadow-logo eclipse wordmark. Do not edit by hand.\n"
    f"export const LOGO = {{ viewBox: \"{vb}\", W: {vb.split()[2]}, H: {vb.split()[3]}, CRIMSON: \"{RED}\",\n"
    f"  wedge: \"{wedge}\",\n  ink: \"{ink}\" }} as const;\n"
)

def wordmark(ink_fill):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}"><title>RedShadow</title>'
            f'<path fill="{RED}" d="{wedge}"/><path fill="{ink_fill}" d="{ink}"/></svg>')
a = root / "backend/apps/reports/assets"
(a / "wordmark-light.svg").write_text(wordmark(PAPER))   # for dark cover
(a / "wordmark-dark.svg").write_text(wordmark(INK))      # for light backgrounds

def icon(size, scale, rx, bg=INK):
    s = size * scale / 100  # O height 100 units -> size*scale px
    tx, ty = size / 2 - 665.3 * s, size / 2 - 50 * s
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}"><title>RedShadow</title>'
            f'<rect width="{size}" height="{size}" rx="{rx}" fill="{bg}"/>'
            f'<g transform="translate({tx:.3f} {ty:.3f}) scale({s:.4f})">'
            f'<path fill="{RED}" d="{wedge}"/><path fill="{PAPER}" d="{o_outer}{o_hole}"/></g></svg>')
pub = root / "frontend/public"
(pub / "favicon.svg").write_text(icon(64, 0.74, 14))
w = pathlib.Path(root / "logo-src/work"); w.mkdir(exist_ok=True)
(w / "apple.svg").write_text(icon(180, 0.66, 0))
(w / "icon.svg").write_text(icon(512, 0.74, 96))
(w / "maskable.svg").write_text(icon(512, 0.46, 0))
(w / "ico.svg").write_text(icon(64, 0.80, 12))
print("ok")
